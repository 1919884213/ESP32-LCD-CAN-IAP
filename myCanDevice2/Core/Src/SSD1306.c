void SSD1306_DrawChar(uint8_t x, uint8_t y, char ch) {
  if (ch < 0x20 || ch > 0x7E) {
    ch = ' ';
  }
  const uint8_t *glyph = s_font6x8[ch - 0x20];

  if (x + 6 > SSD1306_WIDTH || y + 8 > SSD1306_HEIGHT) {
    return;
  }

  for (uint8_t col = 0; col < 6; col++) {
    uint8_t line = glyph[col];
    for (uint8_t row = 0; row < 8; row++) {
      uint8_t bit = (uint8_t)(1u << ((y + row) % 8));
      uint16_t idx = (uint16_t)((y + row) / 8 * SSD1306_WIDTH + (x + col));
      if (line & (1 << row)) {
        s_buffer[idx] |= bit; /* 点亮 */
      } else {
        s_buffer[idx] &= (uint8_t)~bit; /* 熄灭: 覆盖写入消除残影 */
      }
    }
  }
}

void SSD1306_DrawString(uint8_t x, uint8_t y, const char *str) {
  while (*str) {
    SSD1306_DrawChar(x, y, *str);
    x += 6;
    if (x + 6 > SSD1306_WIDTH) {
      break;
    }
    str++;
  }
}
